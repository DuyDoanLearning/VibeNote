// Exposes a small, safe API to the renderer. No Node access leaks into the page.
const { contextBridge, ipcRenderer } = require('electron');

const invoke = (ch) => (...args) => ipcRenderer.invoke(ch, ...args);

contextBridge.exposeInMainWorld('vibe', {
  list: invoke('vault:list'),
  chooseFolder: invoke('vault:choose'),
  read: invoke('note:read'),
  save: invoke('note:save'),
  snapshot: invoke('note:snapshot'),
  create: invoke('note:create'),
  move: invoke('note:move'),
  trash: invoke('note:trash'),
  restore: invoke('note:restore'),
  remove: invoke('note:delete'),
  discard: invoke('note:discard'),
  emptyTrash: invoke('trash:empty'),
  reveal: invoke('note:reveal'),
  attach: invoke('note:attach'),
  pickImages: invoke('note:pick-images'),
  history: invoke('note:history'),
  historyRead: invoke('note:history-read'),
  exportNote: invoke('note:export'),
  createNotebook: invoke('notebook:create'),
  renameNotebook: invoke('notebook:rename'),
  deleteNotebook: invoke('notebook:delete'),
  openWindow: invoke('window:open-note'),
  getSettings: invoke('settings:get'),
  setSettings: invoke('settings:set'),
  popup: invoke('menu:popup'),
  themes: invoke('themes:list'),
  currentTheme: invoke('theme:current'),
  importTheme: invoke('themes:import'),
  linkTitle: invoke('link:title'),
  agent: {
    context: invoke('agent:context'),
    link: invoke('agent:link'),
    unlink: invoke('agent:unlink'),
    send: invoke('agent:send'),
    stop: invoke('agent:stop'),
    setMode: invoke('agent:mode'),
    newChat: invoke('agent:new'),
    reply: invoke('agent:permission-reply'),
    onEvent: (cb) => ipcRenderer.on('agent:event', (_e, d) => cb(d)),
  },
  confluence: {
    status: invoke('confluence:status'),
    signOut: invoke('confluence:sign-out'),
    tree: invoke('confluence:tree'),
    page: invoke('confluence:page'),
    sidecar: invoke('confluence:sidecar'),
    save: invoke('confluence:save'),
    mkdir: invoke('confluence:mkdir'),
    push: invoke('confluence:push'),
    pictures: invoke('confluence:pictures'),
    openPicture: invoke('confluence:open-picture'),
  },
  comments: {
    read: invoke('comments:read'),
    write: invoke('comments:write'),
    ask: invoke('comments:ask'),
    postToConfluence: invoke('confluence:comment'),
  },
  http: { request: invoke('http:request') },
  chats: {
    projects: invoke('chats:projects'),
    list: invoke('chats:list'),
    read: invoke('chats:read'),
    continue: invoke('chats:continue'),
    export: invoke('chats:export'),
  },
  write: {
    start: invoke('write:start'),
    stop: invoke('write:stop'),
    onDelta: (cb) => ipcRenderer.on('write:delta', (_e, d) => cb(d)),
  },
  flushed: () => ipcRenderer.send('app:flushed'),
  onChanged: (cb) => ipcRenderer.on('vault:changed', () => cb()),
  onCommand: (cb) => ipcRenderer.on('command', (_e, cmd) => cb(cmd)),
  onSettings: (cb) => ipcRenderer.on('settings:changed', (_e, s) => cb(s)),
  onTheme: (cb) => ipcRenderer.on('theme:changed', (_e, t) => cb(t)),
});
